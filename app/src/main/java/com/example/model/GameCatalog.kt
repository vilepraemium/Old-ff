    fun poolForRoyale(type: RoyaleType): List<CatalogItem> = when (type) {
        RoyaleType.DIAMOND_ROYALE -> items.filter {
            !it.isStarter && it.category != ItemCategory.WEAPON_SKIN
        }
        RoyaleType.GOLD_ROYALE -> items.filter {
            !it.isStarter && it.category != ItemCategory.WEAPON_SKIN && (it.goldPrice != null || it.rarity == Rarity.RARE)
        }
        RoyaleType.WEAPON_ROYALE -> items.filter {
            !it.isStarter && it.category == ItemCategory.WEAPON_SKIN
        }
    }
